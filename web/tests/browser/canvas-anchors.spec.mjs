import { test, expect } from './fixtures.mjs';

for (const width of [1365, 390, 320]) test(`canvas pin below prompt tags, retained image and fullscreen at ${width}px`, async ({page, context}, testInfo) => {
  await page.setViewportSize({width, height: 900});
  await page.emulateMedia({reducedMotion: 'reduce'});
  await context.addInitScript(() => localStorage.setItem('pictide.first-run-guide.v1', JSON.stringify({version: 1, status: 'dismissed'})));
  await page.request.put('/api/settings/general', {data: {theme: 'dark', language: 'zh-CN'}});
  const firstSize = {width: 832, height: 1216};
  const otherSize = {width: 896, height: 1152};
  expect((await page.request.put('/api/canvas-pools/anchors', {data: {name: 'Anchor sizes', sizes: [firstSize]}})).ok()).toBe(true);
  const backend = (await (await page.request.get('/api/bootstrap')).json()).backends[0];
  backend.canvas_pool_id = 'anchors';
  backend.workflow['4'] = {class_type: 'EmptyLatentImage', inputs: {width: 832, height: 1216}};
  for (const dimension of ['width', 'height']) backend.bindings[dimension] = {node_id: '4', input: dimension};
  expect((await page.request.put('/api/backends/fixture', {data: backend})).ok()).toBe(true);
  await page.goto('/#feed');
  await expect(page.locator('#empty-generate:visible, #image-card:visible').first()).toBeVisible();
  if (await page.locator('#empty-generate').isVisible()) await page.locator('#empty-generate').click();
  await expect(page.locator('#main-image')).toHaveAttribute('src', /\/api\/artifacts\/.+\/image/);
  await expect.poll(() => page.locator('#main-image').evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true);
  expect((await page.request.put('/api/canvas-pools/anchors', {data: {name: 'Anchor sizes', sizes: [firstSize, otherSize]}})).ok()).toBe(true);
  await page.locator('.roam-anchor-trigger').click();
  const row = page.locator('.roam-anchor-canvas');
  const select = page.locator('#roam-canvas-size');
  await expect(row).toBeVisible();
  const image = await page.locator('#main-image').getAttribute('src');
  const requests = [];
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/(jobs|roam\/ensure)$/.test(new URL(request.url()).pathname)) requests.push(request.url()); });
  await select.click();
  await page.getByRole('option', {name: '896×1152', exact: true}).click();
  await expect(select).toContainText('896×1152');
  await expect(row.getByRole('button', {name: '固定当前', exact: true})).toBeEnabled();
  const settings = async () => (await (await page.request.get('/api/settings/roam')).json()).pinned_canvas;
  await expect.poll(settings).toEqual(otherSize);
  expect(await page.locator('#main-image').getAttribute('src')).toBe(image);
  expect(requests).toEqual([]);
  await row.getByRole('button', {name: '固定当前', exact: true}).click();
  await expect.poll(settings).toEqual(firstSize);
  await expect(select).toContainText('832×1216');
  await page.reload();
  await page.locator('.roam-anchor-trigger').click();
  await expect(select).toContainText('832×1216');
  const tags = await page.locator('.roam-anchor-terms').boundingBox();
  const canvas = await row.boundingBox();
  expect(canvas.y).toBeGreaterThanOrEqual(tags.y + tags.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const normal = testInfo.outputPath('canvas-normal.png');
  await page.screenshot({path: normal});
  await testInfo.attach('canvas-normal', {path: normal, contentType: 'image/png'});
  await page.locator('#roam-immersive').click();
  await expect(page.locator('#image-card')).toHaveClass(/immersive/);
  await expect(row).toBeVisible();
  await select.click();
  const menu = page.locator('.roam-canvas-options');
  await expect(menu).toBeVisible();
  expect(await menu.evaluate(element => !document.fullscreenElement || document.fullscreenElement.contains(element))).toBe(true);
  await page.getByRole('option', {name: '896×1152', exact: true}).click();
  await expect(row).toBeVisible();
  await expect.poll(settings).toEqual(otherSize);
  const immersive = testInfo.outputPath('canvas-immersive.png');
  await page.screenshot({path: immersive});
  await testInfo.attach('canvas-immersive', {path: immersive, contentType: 'image/png'});
  await row.getByRole('button', {name: '清除画幅固定', exact: true}).click();
  await expect.poll(settings).toBeNull();
  await expect(select).toContainText('跟随漫游');
  expect(await page.locator('#main-image').getAttribute('src')).toBe(image);
});

test('older image dimensions work without a pool and a failed save can be retried', async ({page, context}) => {
  await context.addInitScript(() => localStorage.setItem('pictide.first-run-guide.v1', JSON.stringify({version: 1, status: 'dismissed'})));
  const backend = (await (await page.request.get('/api/bootstrap')).json()).backends[0];
  backend.workflow['4'] = {class_type: 'EmptyLatentImage', inputs: {width: 832, height: 1216}};
  for (const dimension of ['width', 'height']) backend.bindings[dimension] = {node_id: '4', input: dimension};
  expect((await page.request.put('/api/backends/fixture', {data: backend})).ok()).toBe(true);
  await page.route('**/api/artifacts/*/image', route => route.fulfill({contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="832" height="1216"><rect width="832" height="1216" fill="gray"/></svg>'}));
  await page.goto('/#feed');
  await expect(page.locator('#empty-generate')).toBeVisible();
  await page.locator('#empty-generate').click();
  await page.locator('.roam-anchor-trigger').click();
  const pin = page.locator('.roam-anchor-canvas').getByRole('button', {name: 'Pin current', exact: true});
  await expect(pin).toBeEnabled();
  let fail = true;
  await page.route('**/api/settings/roam', route => {
    if (route.request().method() === 'PUT' && fail) {
      fail = false;
      return route.fulfill({status: 500, contentType: 'application/json', body: JSON.stringify({error: 'Canvas save fixture failure'})});
    }
    return route.continue();
  });
  await pin.click();
  await expect(page.locator('.notification-card[data-state=open]')).toContainText('Canvas save fixture failure');
  await expect(pin).toBeEnabled();
  await expect(page.locator('#roam-canvas-size')).toContainText('Follow Roam');
  await pin.click();
  await expect(page.locator('#roam-canvas-size')).toContainText('832×1216');
  expect((await (await page.request.get('/api/settings/roam')).json()).pinned_canvas).toEqual({width: 832, height: 1216});
});
