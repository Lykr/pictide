"""Persistence contract used by application orchestration and generation tasks.

Implementations own transactions, immutable backend revisions and deletion
tombstones. Domain modules do not import the SQLite adapter.
"""
from typing import Any, ContextManager, Protocol, runtime_checkable


@runtime_checkable
class Storage(Protocol):
    path: Any
    def backends(self) -> list[dict]: ...
    def backend(self, iid: str) -> dict | None: ...
    def save_backend(self, config: dict) -> dict: ...
    def delete_backend(self, iid: str) -> bool: ...
    def detach_workflow(self, identifier: str) -> int: ...

    def jobs(self, limit: int = 100) -> list[dict]: ...
    def job_page(self, page: int) -> dict: ...
    def job(self, iid: str) -> dict | None: ...
    def job_backend(self, iid: str) -> dict | None: ...
    def create_job(self, payload: dict) -> dict: ...
    def create_jobs(self, payload: dict, count: int = 1) -> list[dict]: ...
    def generation_plan(self, request_id: str, digest: str) -> dict | None: ...
    def commit_generation_plan(self, request_id: str, digest: str, plans: list[dict], context: dict, backend: dict) -> dict: ...
    def ensure_roam(self, epoch: str, anchor_id: str | None, target: int, payload: dict | None = None, candidate: dict | None = None) -> dict:
        """Return ready/global pending/roam_pending, pause state and any enqueued job."""
        ...
    def pause_roam(self, epoch: str, message: str) -> None: ...
    def roam_snapshot(self, job_id: str) -> dict | None: ...
    def roam_prompt_reference(self, epoch: str, anchor_id: str | None) -> dict | None: ...
    def roam_view(self, payload: dict | None = None) -> dict: ...
    def next_job(self) -> dict | None: ...
    def cancel_pending_jobs(self) -> int: ...
    def claim_job(self, iid: str) -> bool: ...
    def update_job(self, iid: str, status: str | None = None, **fields) -> dict | None: ...
    def attach_prompt(self, iid: str, prompt_id: str) -> dict | None: ...
    def complete(self, iid: str, outputs: list[dict]) -> None: ...
    def recover_submissions(self) -> None: ...
    def unknown_jobs(self) -> list[dict]: ...

    def counts(self) -> dict: ...
    def artifacts(self, liked: bool = False, limit: int = 200, before: str | None = None, source: str = "all") -> list[dict]: ...
    def artifact_page(self, liked: bool = False, limit: int = 200, before: str | None = None, source: str = "all", around: str | None = None) -> dict: ...
    def artifact(self, iid: str) -> dict | None: ...
    def artifact_source(self, iid: str) -> tuple[dict, dict] | None: ...
    def cache_artifact(self, iid: str, output: dict) -> bool: ...
    def artifact_revision(self) -> int: ...
    def clear_generated(self, iid: str | None = None) -> dict: ...
    def expire_artifacts(self, cutoff: str, limit: int = 100) -> int: ...
    def trim_roam_artifacts(self, max_history: int, limit: int = 100) -> int: ...
    def cleanup_counts(self) -> dict: ...
    def liked_positive_prompts(self, actor_id: str = "local") -> list[str]: ...
    def rate(self, iid: str, value: int | None) -> dict | None: ...

    # Only store maintenance uses this transaction boundary. Application and
    # task code use the operations above and never execute persistence queries.
    def connection(self) -> ContextManager[Any]: ...
